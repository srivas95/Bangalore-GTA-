# Writes the Sketchfab section of MODEL_CREDITS.md (between the sketchfab:begin/end markers) from
# the picks files: every model the Unity bake uses, with its author, link and licence.
# usage: python3 tools/unity/bake/sketchfab_credits.py
import json, os, re
root = os.path.dirname(os.path.abspath(__file__)) + "/../../.."
LIC = {"by": ("CC BY 4.0", "https://creativecommons.org/licenses/by/4.0/"), "cc0": ("CC0 1.0", "https://creativecommons.org/publicdomain/zero/1.0/")}
lines = ["<!-- sketchfab:begin (generated by tools/unity/bake/sketchfab_credits.py) -->", "",
         "## Unity version: models from Sketchfab", "",
         "The Unity version (`unity/`) adds these models from Sketchfab. Each is used under the licence shown.", "",
         "- **Changes:** each model is reoriented and scaled to the game's sizes. Its textures are shrunk and packed into one atlas per model, and its meshes are merged.",
         "- **Vehicles:** the wheels are split off as bones. Glass is drawn opaque and tinted.",
         "- **People:** each is re-posed and re-skinned onto the game's own skeleton.",
         "- **Files:** baked by `tools/unity/bake/models.mjs` into `unity/NammaBengaluru/Assets/Resources/Models/` and `Resources/Baked/pack_atlas*.png`.", ""]
for title, f in [("Vehicles", "sketchfab_vehicles.json"), ("People", "sketchfab_people.json")]:
    p = os.path.join(root, "tools/unity/bake", f)
    if not os.path.exists(p): continue
    used = [m for m in json.load(open(p)) if not m.get("skip") and not m.get("drop") and m.get("licenseSlug") in LIC and (title == "Vehicles" or m.get("baked"))]
    if not used: continue
    lines += [f"### {title}", ""]
    for m in used:
        name, url = LIC[m["licenseSlug"]]
        lines.append(f"- \"{m['name'].strip()}\" (<https://sketchfab.com/3d-models/{m['uid']}>) by {m['author']} (<https://sketchfab.com/{m['author']}>), {name} (<{url}>).")
    lines.append("")
lines.append("<!-- sketchfab:end -->")
cf = os.path.join(root, "MODEL_CREDITS.md")
s = open(cf).read()
block = "\n".join(lines)
s = re.sub(r"<!-- sketchfab:begin.*?<!-- sketchfab:end -->", block, s, flags=re.S) if "sketchfab:begin" in s else s.rstrip("\n") + "\n\n" + block + "\n"
open(cf, "w").write(s)
print("credited", sum(l.startswith('- "') for l in lines), "models")
